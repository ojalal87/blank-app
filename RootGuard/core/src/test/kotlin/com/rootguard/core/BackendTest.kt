package com.rootguard.core

import com.rootguard.core.backend.Iptables
import com.rootguard.core.model.Action
import com.rootguard.core.model.DestinationType
import com.rootguard.core.model.NetworkScope
import com.rootguard.core.model.Protocol
import com.rootguard.core.policy.CompiledRule
import com.rootguard.core.policy.PolicyCompiler
import com.rootguard.core.policy.Rule
import com.rootguard.core.policy.Verdict
import org.junit.jupiter.api.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertNull
import kotlin.test.assertTrue

class BackendTest {
    private val plan = PolicyCompiler.preview(
        Fx.policy(
            Rule("w", "p-browser", Action.DENY, network = NetworkScope.WIFI, protocol = Protocol.TCP, portFrom = 443, portTo = 443),
            Rule("ip", "p-shared", Action.DENY, destinationType = DestinationType.CIDR, destinationValue = "2001:db8::/32"),
            Rule("ok", "p-shared", Action.ALLOW, protocol = Protocol.UDP, portFrom = 1000, portTo = 2000),
        ),
        Fx.principals, Fx.probe(), "cap", "rev-1", 0,
    ).plan!!

    @Test
    fun `restore input touches only the owned chain`() {
        val text = Iptables.restoreInput(plan.chains[0], rejectSupported = true)
        val lines = text.trim().lines()
        assertEquals("*filter", lines.first())
        assertEquals(":RG_OUT - [0:0]", lines[1])
        assertEquals("COMMIT", lines.last())
        assertTrue(lines.drop(2).dropLast(1).all { it.startsWith("-A RG_OUT ") })
        assertTrue("-A RG_OUT -o wlan+ -p tcp -m owner --uid-owner 10123 -m tcp --dport 443 -j REJECT --reject-with tcp-reset" in lines)
        assertTrue("-A RG_OUT -p udp -m owner --uid-owner 10200 -m udp --dport 1000:2000 -j RETURN" in lines)
        listOf("OUTPUT", "INPUT", "FORWARD", "-F", "-X", "fw_", "bw_").forEach { bad -> assertTrue(lines.none { l -> l.startsWith("-A $bad") || l == bad }, bad) }
        assertFalse(Iptables.restoreInput(plan.chains[1], rejectSupported = false).contains("REJECT"))
    }

    @Test
    fun `iptables-save read-back round-trips to the same hash`() {
        for (chain in plan.chains) {
            val save = buildString {
                append("# Generated by iptables-save\n*filter\n:INPUT ACCEPT [0:0]\n:OUTPUT ACCEPT [0:0]\n:fw_OUTPUT - [0:0]\n:RG_OUT - [0:0]\n")
                append("-A OUTPUT -j RG_OUT\n-A OUTPUT -j fw_OUTPUT\n")
                // iptables-save prints host addresses with an explicit prefix and keeps module order.
                Iptables.restoreInput(chain, true).lines().filter { it.startsWith("-A RG_OUT") }.forEach { append(it).append('\n') }
                append("COMMIT\n")
            }
            val rb = Iptables.parseSave(chain.family, save)
            assertTrue(rb.chainPresent)
            assertEquals(1, rb.hookCount)
            assertTrue(rb.hookFirst)
            assertEquals(emptyList(), rb.unparsed)
            assertEquals(PolicyCompiler.familyHash(chain.family, chain.rules), rb.hash)
        }
    }

    @Test
    fun `foreign or modified rules in the owned chain are reported, not guessed`() {
        val rb = Iptables.parseSave(4, "*filter\n:RG_OUT - [0:0]\n:afwall - [0:0]\n-A RG_OUT -m mark --mark 0x1 -j ACCEPT\nCOMMIT\n")
        assertEquals(1, rb.unparsed.size)
        assertEquals(0, rb.hookCount)
        assertEquals(listOf("afwall"), rb.foreignChains)
        assertTrue(Iptables.parseSave(4, "*nat\n:RG_OUT - [0:0]\nCOMMIT\n").empty)
    }

    @Test
    fun `helper re-validation rejects tampered plans`() {
        assertNull(Iptables.validate(plan))
        val tampered = plan.copy(chains = plan.chains.map { c -> c.copy(rules = c.rules + CompiledRule(c.family, verdict = Verdict.DENY, sourceRuleId = "x")) })
        assertEquals(Iptables.PlanError.HASH_MISMATCH, Iptables.validate(tampered))
        fun withRule(r: CompiledRule) = plan.copy(chains = listOf(com.rootguard.core.policy.ChainPlan(4, listOf(r)))).let { it.copy(canonicalHash = PolicyCompiler.hash(it.chains)) }
        assertEquals(Iptables.PlanError.BAD_INTERFACE, Iptables.validate(withRule(CompiledRule(4, outInterface = "wlan0;reboot", verdict = Verdict.DENY, sourceRuleId = "x"))))
        assertEquals(Iptables.PlanError.BAD_DESTINATION, Iptables.validate(withRule(CompiledRule(4, destination = "2001:db8::/32", verdict = Verdict.DENY, sourceRuleId = "x"))))
        assertEquals(Iptables.PlanError.BAD_DESTINATION, Iptables.validate(withRule(CompiledRule(4, destination = "10.0.0.1/8", verdict = Verdict.DENY, sourceRuleId = "x"))))
        assertEquals(Iptables.PlanError.BAD_PORTS, Iptables.validate(withRule(CompiledRule(4, portFrom = 1, portTo = 2, verdict = Verdict.DENY, sourceRuleId = "x"))))
        assertEquals(Iptables.PlanError.BAD_UID, Iptables.validate(withRule(CompiledRule(4, uidStart = 5, uidEnd = 1, verdict = Verdict.DENY, sourceRuleId = "x"))))
        assertEquals(Iptables.PlanError.BAD_ID, Iptables.validate(withRule(CompiledRule(4, verdict = Verdict.DENY, sourceRuleId = "x y"))))
    }

    @Test
    fun `single-operation argv never contains global flush or built-in chain edits other than the own hook`() {
        val all = listOf(4, 6).flatMap { f ->
            listOf(Iptables.hookCheck(f, true), Iptables.hookInsert(f, true), Iptables.hookDelete(f, true), Iptables.chainFlush(f, true), Iptables.chainDelete(f, true), Iptables.restore(f, true))
        }
        all.forEach { argv ->
            assertTrue(argv[0].startsWith("/system/bin/"))
            if ("-F" in argv || "-X" in argv) assertTrue(argv.last() == Iptables.CHAIN, argv.toString())
            if ("OUTPUT" in argv) assertTrue(argv.last() == Iptables.CHAIN)
        }
    }
}
