/**
 * In-memory model of iptables/ip6tables filter tables, enough to exercise the helper end to end without
 * touching any real firewall. OUTPUT starts with netd-like and foreign rules that must survive untouched.
 */
class FakeIptables : Exec {
    inner class Table {
        val chains = linkedMapOf<String, MutableList<String>>("fw_OUTPUT" to mutableListOf("-j RETURN"), "bw_OUTPUT" to mutableListOf())
        val output = mutableListOf("-j fw_OUTPUT", "-j bw_OUTPUT")
    }
    val tables = mapOf(4 to Table(), 6 to Table())
    var failRestore: Int? = null
    var ownerUnsupported = false
    val calls = ArrayList<List<String>>()

    private fun fam(bin: String) = if (bin.contains("ip6tables")) 6 else 4

    override fun run(argv: List<String>, stdin: String?): ExecResult {
        calls += argv
        require(argv.none { it == "sh" || it == "-c" }) { "no shell" }
        val f = fam(argv[0]); val t = tables.getValue(f)
        val a = argv.drop(1).filter { it != "-w" }
        return when {
            argv[0].endsWith("-save") -> ExecResult(0, save(t))
            argv[0].endsWith("-restore") -> restore(f, t, stdin.orEmpty())
            a == listOf("-V") -> ExecResult(0, "iptables v1.8.7")
            a.take(3) == listOf("-t", "filter", "-S") -> ExecResult(0, "")
            a.take(3) == listOf("-t", "filter", "-C") -> ExecResult(if (rule(a.drop(4)) in t.output) 0 else 1, "")
            a.take(3) == listOf("-t", "filter", "-I") -> { t.output.add(0, rule(a.drop(5))); ExecResult(0, "") }
            a.take(3) == listOf("-t", "filter", "-D") -> ExecResult(if (t.output.remove(rule(a.drop(4)))) 0 else 1, "")
            a.take(3) == listOf("-t", "filter", "-F") -> t.chains[a[3]]?.let { it.clear(); ExecResult(0, "") } ?: ExecResult(1, "no chain")
            a.take(3) == listOf("-t", "filter", "-X") -> {
                val name = a[3]
                if (t.chains[name]?.isEmpty() == true && t.output.none { it == "-j $name" }) { t.chains.remove(name); ExecResult(0, "") } else ExecResult(1, "busy")
            }
            a.take(3) == listOf("-t", "filter", "-N") -> { t.chains.putIfAbsent(a[3], mutableListOf()); ExecResult(0, "") }
            a.take(3) == listOf("-t", "filter", "-A") -> {
                val ch = t.chains[a[3]] ?: return ExecResult(1, "no chain")
                if (ownerUnsupported && "--uid-owner" in a) return ExecResult(1, "no owner match")
                ch += rule(a.drop(4)); ExecResult(0, "")
            }
            else -> ExecResult(2, "unsupported in fake: $a")
        }
    }

    private fun rule(parts: List<String>) = parts.joinToString(" ")

    private fun restore(f: Int, t: Table, input: String): ExecResult {
        if (failRestore == f) return ExecResult(1, "simulated failure")
        val staged = t.chains.mapValues { it.value.toMutableList() }.toMutableMap()
        for (line in input.lines()) {
            when {
                line == "*filter" || line == "COMMIT" || line.isBlank() -> Unit
                line.startsWith(":") -> staged[line.substring(1).substringBefore(' ')] = mutableListOf()
                line.startsWith("-A ") -> {
                    val name = line.split(' ')[1]
                    if (ownerUnsupported && "--uid-owner" in line) return ExecResult(1, "no owner match")
                    staged[name]?.add(line.substringAfter("-A $name ")) ?: return ExecResult(1, "no chain $name")
                }
                else -> return ExecResult(1, "bad line")
            }
        }
        t.chains.clear(); t.chains.putAll(staged) // one atomic commit
        return ExecResult(0, "")
    }

    private fun save(t: Table) = buildString {
        append("# Generated by fake\n*filter\n:INPUT ACCEPT [0:0]\n:FORWARD ACCEPT [0:0]\n:OUTPUT ACCEPT [0:0]\n")
        t.chains.keys.forEach { append(":$it - [0:0]\n") }
        t.output.forEach { append("-A OUTPUT $it\n") }
        t.chains.forEach { (n, rules) -> rules.forEach { append("-A $n $it\n") } }
        append("COMMIT\n")
    }
}

class FakeSys(private val ifaces: List<String> = listOf("lo", "wlan0", "rmnet_data0", "dummy0")) : SysInfo {
    override fun selinuxEnforcing() = true
    override fun netInterfaces() = ifaces
    override fun binaryExists(path: String) = true
}

class MemJournal : JournalStore {
    var j: HelperJournal? = null
    override fun read() = j
    override fun write(j: HelperJournal) { this.j = j }
}
