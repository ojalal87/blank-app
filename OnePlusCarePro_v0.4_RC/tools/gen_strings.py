#!/usr/bin/env python3
"""Generate values/strings.xml and values-ar/strings.xml from tools/strings_part*.py and verify
that (1) every R.string key used in app sources exists, (2) no key is unused, (3) English and Arabic
use identical positional format specifiers. Run: python3 -I tools/gen_strings.py <project root>"""
import re, sys, pathlib, runpy

root = pathlib.Path(sys.argv[1])
entries = []
for part in sorted((root / "tools").glob("strings_part*.py")):
    entries += runpy.run_path(str(part))["S"]

keys = [k for k, _, _ in entries]
dups = {k for k in keys if keys.count(k) > 1}
errors = []
if dups: errors.append(f"duplicate keys: {sorted(dups)}")

src = "\n".join(p.read_text(encoding="utf-8") for p in (root / "app/src/main/java").rglob("*.kt"))
used = set(re.findall(r"R\.string\.([a-z0-9_]+)", src))
missing = used - set(keys)
unused = set(keys) - used - {"app_name"}
if missing: errors.append(f"missing: {sorted(missing)}")
if unused: errors.append(f"unused: {sorted(unused)}")

spec = re.compile(r"%(\d+)\$([ds])")
for k, en, ar in entries:
    if sorted(spec.findall(en)) != sorted(spec.findall(ar)):
        errors.append(f"format mismatch in {k}: {spec.findall(en)} vs {spec.findall(ar)}")
    for text in (en, ar):
        if re.search(r"%(?!\d+\$[ds])", text):
            errors.append(f"stray % in {k}")

def esc(s):
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    if s[:1] in ("@", "?"): s = "\\" + s
    return s

def write(path, idx, header):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {header} -->", "<resources>"]
    for e in entries:
        k = e[0]
        attrs = ' translatable="false"' if k == "app_name" else ""
        if k == "app_name" and idx == 2: continue
        lines.append(f'    <string name="{k}"{attrs}>{esc(e[idx])}</string>')
    lines.append("</resources>")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")

write(root / "app/src/main/res/values/strings.xml", 1, "Generated by tools/gen_strings.py. Edit tools/strings_part*.py instead.")
write(root / "app/src/main/res/values-ar/strings.xml", 2, "Generated by tools/gen_strings.py. Edit tools/strings_part*.py instead.")
print(f"{len(entries)} strings, {len(used)} referenced")
if errors:
    print("\n".join(errors)); sys.exit(1)
print("OK")
